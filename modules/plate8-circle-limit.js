/* PLATE VIII — "Circle Limit"                        window.EscherPlate8
   A genuine Poincaré-disk {6,4} tessellation. Geodesics are true circular
   arcs meeting the boundary at right angles; tiles are generated by Mobius
   reflections of a fundamental characteristic triangle and shrink toward
   the rim without ever reaching it. Drag applies a hyperbolic translation
   and the tiling regenerates at the horizon, so travel is unbounded: the
   readout's hyperbolic distance climbs forever while DISTANCE TO RIM stays
   ∞. Math verified in tests/hyperbolic-math.test.js. */
(function () {
  'use strict';

  // ---- complex arithmetic on {re, im} -------------------------------
  var C = function (re, im) { return { re: re, im: im || 0 }; };
  function cadd(a, b) { return C(a.re + b.re, a.im + b.im); }
  function csub(a, b) { return C(a.re - b.re, a.im - b.im); }
  function cmul(a, b) { return C(a.re * b.re - a.im * b.im, a.re * b.im + a.im * b.re); }
  function cconj(a) { return C(a.re, -a.im); }
  function cabs2(a) { return a.re * a.re + a.im * a.im; }
  function cabs(a) { return Math.hypot(a.re, a.im); }
  function cscale(a, s) { return C(a.re * s, a.im * s); }
  function cdiv(a, b) {
    var d = cabs2(b);
    return C((a.re * b.re + a.im * b.im) / d, (a.im * b.re - a.re * b.im) / d);
  }

  // ---- Mobius disc automorphism  z -> (a z + c)/(c̄ z + ā) -----------
  // stored as {a, c, flip}; flip=true precomposes conjugation (a true
  // reflection, orientation-reversing). |a|²-|c|²=1 keeps it in the disc.
  function X(a, c, flip) { return { a: a, c: c, flip: !!flip }; }
  var IDENT = X(C(1, 0), C(0, 0), false);

  function applyX(t, z) {
    var w = t.flip ? cconj(z) : z;
    return cdiv(cadd(cmul(t.a, w), t.c), cadd(cmul(cconj(t.c), w), cconj(t.a)));
  }
  // group law honouring the anti-linear flip bit (conjugate the right
  // matrix's entries when the left map is orientation-reversing).
  function compose(t1, t2) {
    var a2 = t2.a, c2 = t2.c;
    if (t1.flip) { a2 = cconj(a2); c2 = cconj(c2); }
    return X(
      cadd(cmul(t1.a, a2), cmul(t1.c, cconj(c2))),
      cadd(cmul(t1.a, c2), cmul(t1.c, cconj(a2))),
      t1.flip !== t2.flip
    );
  }
  function normX(t) { // guard float drift: renormalize |a|²-|c|²=1
    var det = cabs2(t.a) - cabs2(t.c);
    var s = 1 / Math.sqrt(Math.abs(det));
    return X(cscale(t.a, s), cscale(t.c, s), t.flip);
  }
  // pure hyperbolic translation moving origin -> w :  z -> (z+w)/(1+w̄z)
  function translation(w) { return normX(X(C(1, 0), w, false)); }
  function hypDistOrigin(z) { return 2 * atanh(Math.min(cabs(z), 1 - 1e-12)); }
  function atanh(x) { return 0.5 * Math.log((1 + x) / (1 - x)); }

  // inverse of a disc automorphism (needed to locate the basepoint view⁻¹(0)).
  // orientation-preserving z→(az+c)/(c̄z+ā):  inverse is X(ā, −c). For a reflection
  // (flip) the inverse is X(−a, c̄) with the flip kept — derived from f⁻¹(w)=
  // conj((−ā w + c)/(c̄ w − a)); verified by round-trip in tests.
  function invX(t) {
    if (!t.flip) return normX(X(cconj(t.a), cscale(t.c, -1), false));
    return normX(X(cscale(t.a, -1), cconj(t.c), true));
  }

  // ---- the {p,q} fundamental triangle & its three edge-mirrors ------
  // {6,4}: 1/6+1/4 = 5/12 < 1/2  (hyperbolic). Six-fold rosettes of wing-figures.
  var P = 6, Q = 4;
  function buildGenerators() {
    var pp = Math.PI / P, qq = Math.PI / Q;
    // {p,q} vertex ring Euclidean radius (standard construction):
    var rB = Math.sqrt(Math.cos(pp + qq) / Math.cos(pp - qq));
    var A = C(0, 0);            // p-fold centre at origin
    var B = C(rB, 0);          // q-fold vertex on +x axis
    // Edge AB is the x-diameter; edge AC is the diameter at angle π/p; edge BC is
    // the circle orthogonal to |z|=1 through B: centre k>1 on +x with k²−ρ²=1 and
    // (k−rB)²=ρ²  ⇒  k=(1+rB²)/(2rB), ρ=√(k²−1).
    var k = (1 + rB * rB) / (2 * rB);
    var rho = Math.sqrt(k * k - 1);
    // 2-fold vertex Cc = ray(angle π/p) ∩ circle(k,ρ):  solve for radius t.
    var bq = -2 * k * Math.cos(pp);
    var t = (-bq - Math.sqrt(bq * bq - 4)) / 2;
    var Cc = C(t * Math.cos(pp), t * Math.sin(pp));
    // The three edge mirrors (all orientation-reversing). Each FIXES its edge
    // pointwise (verified in tests) — the subtlety is that applyX divides by ā, so
    // a line reflection z→e^{2iθ}z̄ needs a=e^{iθ} (not e^{2iθ}); and the circle
    // inversion (kz̄−1)/(z̄−k) normalises to a=i·k/ρ, c=−i/ρ (a real-matrix form
    // would inject a spurious point-reflection through the origin).
    var mAB = X(C(1, 0), C(0, 0), true);                             // reflect across x-axis
    var mAC = X(C(Math.cos(pp), Math.sin(pp)), C(0, 0), true);       // reflect across line ∠π/p
    var mBC = X(C(0, k / rho), C(0, -1 / rho), true);                // inversion in circle(k,ρ)
    return { gens: [mAB, mAC, mBC], A: A, B: B, Cc: Cc, rB: rB, k: k, rho: rho, pp: pp };
  }
  var G = buildGenerators();

  // ---- geodesic arc between two disc points -------------------------
  // The geodesic is the circle orthogonal to |z|=1 through z1,z2. Its
  // centre m satisfies |m|² = 1 + R² and lies on the perpendicular data
  // of the chord; solved from the two "power of point" equations.
  function geodesicArc(ctx, z1, z2, unitR, cx, cy) {
    var d = z1.re * z2.im - z1.im * z2.re; // cross product
    if (Math.abs(d) < 1e-9) { // collinear with origin -> straight diameter
      ctx.moveTo(cx + z1.re * unitR, cy - z1.im * unitR);
      ctx.lineTo(cx + z2.re * unitR, cy - z2.im * unitR);
      return;
    }
    var s1 = cabs2(z1) + 1, s2 = cabs2(z2) + 1;
    var mx = (z2.im * s1 - z1.im * s2) / (2 * d);
    var my = (z1.re * s2 - z2.re * s1) / (2 * d);
    var R = Math.sqrt(mx * mx + my * my - 1);
    // canvas coords (flip y). angles measured in canvas space.
    var Mx = cx + mx * unitR, My = cy - my * unitR, Rp = R * unitR;
    var a1 = Math.atan2(-(z1.im - my), z1.re - mx);
    var a2 = Math.atan2(-(z2.im - my), z2.re - mx);
    // choose the minor arc (the geodesic never wraps the long way)
    var da = a2 - a1;
    while (da > Math.PI) da -= 2 * Math.PI;
    while (da < -Math.PI) da += 2 * Math.PI;
    ctx.arc(Mx, My, Rp, a1, a1 + da, da < 0);
  }

  // ---- CSS (scoped under .plate--circle-limit per contract) ---------
  var CSS = [
    '.plate--circle-limit{position:relative;display:flex;flex-direction:column;align-items:center;padding:clamp(1.5rem,4vw,3.5rem) 1rem 2.75rem;background:var(--paper);color:var(--ink);}',
    '.plate--circle-limit .pl8-eyebrow{font-family:var(--font-mono);text-transform:uppercase;letter-spacing:.28em;font-size:.62rem;color:var(--ink-2);margin-bottom:.6rem;}',
    '.plate--circle-limit .pl8-title{font-family:var(--font-display);font-weight:700;font-size:clamp(2rem,5.5vw,3.4rem);line-height:.98;letter-spacing:-.01em;margin:0 0 1.1rem;}',
    '.plate--circle-limit .pl8-stage{position:relative;width:min(88vw,640px);aspect-ratio:1/1;outline:none;cursor:grab;touch-action:none;}',
    '.plate--circle-limit .pl8-stage:active{cursor:grabbing;}',
    '.plate--circle-limit .pl8-stage:focus-visible{box-shadow:0 0 0 2px var(--paper),0 0 0 4px var(--teal);border-radius:50%;}',
    '.plate--circle-limit canvas{display:block;width:100%;height:100%;}',
    '.plate--circle-limit .pl8-readout{font-family:var(--font-mono);text-transform:uppercase;letter-spacing:.16em;font-size:.64rem;color:var(--ink-2);margin-top:1.2rem;text-align:center;display:grid;grid-template-columns:repeat(2,auto);gap:.25em 2.2em;justify-content:center;}',
    '.plate--circle-limit .pl8-readout b{color:var(--ink);font-weight:400;}',
    '.plate--circle-limit .pl8-rim{color:var(--teal);}',
    '.plate--circle-limit .pl8-rim b{color:var(--teal);font-size:.9rem;}',
    '.plate--circle-limit .pl8-ctrl{margin-top:1.15rem;}',
    '.plate--circle-limit .pl8-btn{font-family:var(--font-mono);text-transform:uppercase;letter-spacing:.2em;font-size:.6rem;color:var(--ink);background:transparent;border:1px solid color-mix(in srgb,var(--ink) 45%,var(--paper));padding:.6em 1.15em;cursor:pointer;transition:background .18s,color .18s;}',
    '.plate--circle-limit .pl8-btn:hover{background:var(--ink);color:var(--paper);}',
    '.plate--circle-limit .pl8-btn:focus-visible{outline:2px solid var(--teal);outline-offset:2px;}',
    '.plate--circle-limit .pl8-label{max-width:34rem;margin:1.6rem auto 0;text-align:center;font-family:var(--font-body);font-size:.92rem;line-height:1.55;color:var(--ink-2);}',
    '.plate--circle-limit .pl8-label em{color:var(--ink);}',
    '.plate--circle-limit .pl8-epigraph{font-family:var(--font-body);font-style:italic;font-size:.86rem;color:var(--ink-2);max-width:30rem;margin:.9rem auto 0;text-align:center;}'
  ].join('\n');

  // ---- module -------------------------------------------------------
  window.EscherPlate8 = {
    id: 'circle-limit',
    css: CSS,

    mount: function (root, api) {
      root.classList.add('plate--circle-limit');
      root.innerHTML =
        '<div class="pl8-eyebrow">Plate VIII · Regular Division of the Plane</div>' +
        '<h2 class="pl8-title">Circle Limit</h2>' +
        '<div class="pl8-stage" id="pl8-stage" tabindex="0" role="application" ' +
          'aria-label="Hyperbolic tiling in a Poincaré disk. Drag or use arrow keys to travel; ' +
          'the tiles shrink toward the rim but the edge is infinitely far away.">' +
          '<canvas id="pl8-canvas" aria-hidden="true"></canvas>' +
        '</div>' +
        '<div class="pl8-readout" aria-live="polite">' +
          '<span>TILING</span><span><b id="pl8-pq">{6,4}</b></span>' +
          '<span>TILES DRAWN</span><span><b id="pl8-tiles">0</b></span>' +
          '<span>HYPERBOLIC DISTANCE</span><span><b id="pl8-dist">0.000</b></span>' +
          '<span class="pl8-rim">DISTANCE TO RIM</span><span class="pl8-rim"><b>&#8734;</b></span>' +
        '</div>' +
        '<div class="pl8-ctrl"><button type="button" class="pl8-btn" id="pl8-home" ' +
          'aria-label="Return to the centre of the disc">Return to Centre</button></div>' +
        '<p class="pl8-label">A <em>{6,4}</em> tessellation of the hyperbolic plane, drawn in the ' +
          'Poincaré disk. Every wing is the same size; only Euclidean eyes see them shrink. ' +
          'Travel as far as you like — the rim recedes at exactly the rate you approach it.</p>' +
        '<p class="pl8-epigraph">The finite frame holds an infinite floor: no journey spends it, ' +
          'no step arrives.</p>';

      var stage = root.querySelector('#pl8-stage');
      var canvas = root.querySelector('#pl8-canvas');
      var ctx = canvas.getContext && canvas.getContext('2d');
      var elTiles = root.querySelector('#pl8-tiles');
      var elDist = root.querySelector('#pl8-dist');
      var elHome = root.querySelector('#pl8-home');
      if (!ctx) { // graceful: no canvas -> leave the static label as the plate's content
        return { destroy: function () { root.classList.remove('plate--circle-limit'); } };
      }

      // view = the Mobius transform from tiling-space to screen; we pre-apply it
      // to every tile transform when rendering. It is kept well-conditioned by
      // re-rooting each travel step (see travelBy). odometer = total hyperbolic
      // distance travelled, accumulated separately so it can climb without bound.
      var view = IDENT;
      var odometer = 0;
      var W = 0, H = 0, cx = 0, cy = 0, unitR = 0, dpr = 1;
      var reduced = api.reducedMotion;

      // pixel radius of the disc rim, minus a hair so the hairline sits inside.
      function resize() {
        var rect = stage.getBoundingClientRect();
        dpr = Math.max(1, Math.min(window.devicePixelRatio || 1, 2));
        W = Math.max(1, Math.round(rect.width));
        H = Math.max(1, Math.round(rect.height));
        canvas.width = Math.round(W * dpr);
        canvas.height = Math.round(H * dpr);
        cx = (W * dpr) / 2;
        cy = (H * dpr) / 2;
        unitR = Math.min(cx, cy) - 2 * dpr;
        needsDraw = true;
      }

      // ---- colour: 4-colouring from BFS depth + flip parity ----------
      function tileColour(depth, flip) {
        var idx = ((depth % 3) + (flip ? 1 : 0)) % 4;
        // resolve CSS custom properties against the live root (day/night aware)
        var vars = ['--ink', '--bistre', '--teal', '--paper-2'];
        return getVar(vars[idx]);
      }
      var _varCache = {};
      function getVar(name) {
        if (_varCache[name]) return _varCache[name];
        var v = getComputedStyle(root).getPropertyValue(name).trim() || '#000';
        _varCache[name] = v;
        return v;
      }
      function clearVarCache() { _varCache = {}; }

      // ---- the wing motif inside the fundamental domain --------------
      // a stylised wing: a closed loop of geodesic arcs through points inside
      // the characteristic triangle (A, B, Cc), filled as a silhouette with an
      // eye added when the tile is large enough (LOD).
      var Bpt = G.B, Cpt = G.Cc;
      function lerp(z1, z2, s) { return C(z1.re + (z2.re - z1.re) * s, z1.im + (z2.im - z1.im) * s); }
      var wing = {
        // silhouette ring (tiling-space points), a stylised wing:
        ring: [
          C(0, 0),
          lerp(G.A, Bpt, 0.55),
          lerp(Bpt, Cpt, 0.32),
          Cpt,
          lerp(Cpt, G.A, 0.45),
          lerp(Cpt, G.A, 0.82)
        ],
        eye: lerp(lerp(G.A, Bpt, 0.5), Cpt, 0.35)
      };
      // a fixed interior point of the fundamental triangle (its rough centroid).
      var CENTROID = lerp(lerp(G.A, Bpt, 0.34), Cpt, 0.5);

      // Fold the view's basepoint back into the fundamental triangle — the engine
      // of unbounded, stable travel. After a translation, q = view⁻¹(0) may drift
      // out of the domain; we reflect it back across each wall it violates (and
      // compose that mirror onto the view) until it is inside all three. The tiling
      // is homogeneous so the picture is seamless, yet the view matrix stays
      // conditioned forever (entries ~1 even after 10⁵ steps) and |z| never blows up.
      // violation(q,i) > 0 ⇔ q on the wrong side of wall i:
      //   0 x-axis (inside im≥0): −q.im   1 line∠π/p (arg≤π/p): cos·q.im−sin·q.re
      //   2 circle(k,ρ) (inside |q−k|≥ρ): ρ−|q−k|
      var SINP = Math.sin(G.pp), COSP = Math.cos(G.pp);
      function violation(q, i) {
        if (i === 0) return -q.im;
        if (i === 1) return COSP * q.im - SINP * q.re;
        return G.rho - Math.hypot(q.re - G.k, q.im);
      }
      function reduce() {
        var guard = 0;
        while (guard++ < 400) {
          var q = applyX(invX(view), C(0, 0));
          var worst = 1e-9, bi = -1;
          for (var i = 0; i < G.gens.length; i++) {
            var v = violation(q, i);
            if (v > worst) { worst = v; bi = i; }
          }
          if (bi < 0) break;              // inside the fundamental domain: done
          view = normX(compose(view, G.gens[bi]));
        }
      }

      function drawTileFigure(t, px, depth) {
        var r = wing.ring, i;
        // map ring through the tile transform (already includes `view`)
        var pts = new Array(r.length);
        for (i = 0; i < r.length; i++) pts[i] = applyX(t, r[i]);
        ctx.beginPath();
        var s = pts[0];
        ctx.moveTo(cx + s.re * unitR, cy - s.im * unitR);
        for (i = 0; i < pts.length; i++) {
          geodesicArc(ctx, pts[i], pts[(i + 1) % pts.length], unitR, cx, cy);
        }
        ctx.closePath();
        ctx.fillStyle = tileColour(depth, t.flip);
        ctx.globalAlpha = 0.92;
        ctx.fill();
        ctx.globalAlpha = 1;
        // engraved edge
        ctx.lineWidth = Math.max(0.4, Math.min(1.2, px * 0.05)) * dpr;
        ctx.strokeStyle = getVar('--ink');
        ctx.stroke();
        // LOD: spine + eye only while the tile reads (> ~14 px across)
        if (px > 14 * dpr) {
          var e = applyX(t, wing.eye);
          ctx.beginPath();
          ctx.arc(cx + e.re * unitR, cy - e.im * unitR, Math.max(0.8, px * 0.045), 0, 2 * Math.PI);
          ctx.fillStyle = getVar('--paper');
          ctx.fill();
        }
      }

      // ---- generate + render the tiling ------------------------------
      function render() {
        var cw = canvas.width, ch = canvas.height;
        // paper ground for the well
        ctx.clearRect(0, 0, cw, ch);
        // clip to the disc so nothing spills past the rim
        ctx.save();
        ctx.beginPath();
        ctx.arc(cx, cy, unitR, 0, 2 * Math.PI);
        ctx.clip();
        // faint plate-well fill
        ctx.fillStyle = getVar('--paper');
        ctx.fillRect(0, 0, cw, ch);

        // BFS over the group, each transform pre-composed with the view, dedup by
        // matrix key. reduce() keeps the basepoint in the domain, so `view` is the
        // tile over screen-centre and BFS fans outward filling the disc. Horizon: a
        // tile is drawn but not expanded once its screen size < ~0.6px (the real
        // edge of the infinity); tiles just past the rim (rc<1.06) still expand so
        // the frontier wraps correctly.
        var seed = normX(view);
        var seen = Object.create(null);
        var queue = [{ t: seed, depth: 0 }];
        seen[keyOf(seed)] = 1;
        var drawn = 0, MAXT = reduced ? 3200 : 6000;
        var minPx = 0.6 * dpr;
        for (var qi = 0; qi < queue.length && drawn < MAXT; qi++) {
          var node = queue[qi];
          var t = node.t;
          var ia = applyX(t, G.A), ib = applyX(t, G.B);
          var px = cabs(csub(ib, ia)) * unitR;          // on-screen tile size
          var rc = cabs(ia);                             // centre radius in disc
          if (rc < 1.004) {                              // centre within disc (tiny margin)
            if (px > 2.2 * dpr) drawTileFigure(t, px, node.depth);
            else {                                       // sub-pixel ink stipple keeps the rim alive
              ctx.fillStyle = tileColour(node.depth, t.flip);
              ctx.globalAlpha = 0.7;
              ctx.fillRect(cx + ia.re * unitR, cy - ia.im * unitR, Math.max(0.6, px), Math.max(0.6, px));
              ctx.globalAlpha = 1;
            }
            drawn++;
          }
          // Expand toward neighbours while this tile is plausibly near the disc
          // AND still above the pixel horizon. Expanding slightly-outside tiles
          // (rc < 1.06) lets the frontier wrap around the rim correctly.
          if (px < minPx || rc > 1.06) continue;
          for (var gi = 0; gi < G.gens.length; gi++) {
            var nt = normX(compose(t, G.gens[gi]));
            var kk = keyOf(nt);
            if (!seen[kk]) { seen[kk] = 1; queue.push({ t: nt, depth: node.depth + 1 }); }
          }
        }
        ctx.restore();

        // boundary circle — crisp hand-inked hairline, double-stroked to live a little
        ctx.beginPath();
        ctx.arc(cx, cy, unitR, 0, 2 * Math.PI);
        ctx.strokeStyle = getVar('--ink');
        ctx.lineWidth = 1.25 * dpr;
        ctx.stroke();
        ctx.beginPath();
        ctx.arc(cx, cy, unitR - 1.5 * dpr, 0, 2 * Math.PI);
        ctx.globalAlpha = 0.35;
        ctx.lineWidth = 0.5 * dpr;
        ctx.stroke();
        ctx.globalAlpha = 1;

        elTiles.textContent = String(drawn);
        elDist.textContent = odometer.toFixed(3); // total hyperbolic distance travelled
      }
      // Dedup key. Canonicalise the ±sign first: X(a,c) and X(−a,−c) are the SAME
      // Möbius map, so without this every tile would be generated twice (halving the
      // budget and double-inking every edge). Force a.re>0 (tie-break a.im>0).
      function keyOf(t) {
        var a = t.a, c = t.c;
        if (a.re < -1e-9 || (a.re <= 1e-9 && a.re >= -1e-9 && a.im < -1e-9)) {
          a = cscale(a, -1); c = cscale(c, -1);
        }
        var r = function (x) { return Math.round(x * 1e4) / 1e4; };
        return r(a.re) + ',' + r(a.im) + ',' + r(c.re) + ',' + r(c.im) + ',' + (t.flip ? 1 : 0);
      }

      // ---- travel ----------------------------------------------------
      // Drag delta (dx,dy) → a hyperbolic translation of the view. The odometer
      // accumulates true distance (+= 2·atanh(|step|)) so it climbs forever, while
      // reduce() (above) keeps the view matrix conditioned. Distance is unbounded;
      // the picture never degrades.
      function travelBy(dxPx, dyPx) {
        var f = 1.15 / unitR;                 // px -> disc; ~full-radius drag ≈ one step
        var w = C(dxPx * f, -dyPx * f);
        var wl = cabs(w);
        if (wl > 0.6) w = cscale(w, 0.6 / wl); // cap per-step so a fast drag stays sane
        odometer += 2 * atanh(Math.min(cabs(w), 1 - 1e-12));
        view = normX(compose(translation(w), view));
        reduce();                              // fold basepoint into fundamental domain
        needsDraw = true;
      }

      // ---- animation / redraw scheduling ----------------------------
      var needsDraw = true;
      var visible = false;
      var loop = api.raf(function () {
        if (needsDraw) { needsDraw = false; render(); }
      });

      // ---- pointer drag (skip in reduced-motion) --------------------
      var dragging = false, lastX = 0, lastY = 0;
      function onDown(e) {
        if (reduced) return;
        dragging = true;
        stage.setPointerCapture && stage.setPointerCapture(e.pointerId);
        lastX = e.clientX; lastY = e.clientY;
      }
      function onMove(e) {
        if (!dragging) return;
        var dx = e.clientX - lastX, dy = e.clientY - lastY;
        lastX = e.clientX; lastY = e.clientY;
        travelBy(dx, dy);
        loop.start();
      }
      function onUp(e) {
        dragging = false;
        stage.releasePointerCapture && stage.releasePointerCapture(e.pointerId);
      }
      if (!reduced) {
        stage.addEventListener('pointerdown', onDown);
        stage.addEventListener('pointermove', onMove);
        stage.addEventListener('pointerup', onUp);
        stage.addEventListener('pointercancel', onUp);
      }

      // ---- return to centre — the only way back (you cannot walk out) --
      function recenter() { view = IDENT; odometer = 0; needsDraw = true; render(); }

      // ---- keyboard parity (also present in reduced-motion) ---------
      function onKey(e) {
        var step = 42; // px, ~ one comfortable hyperbolic stride
        var handled = true;
        if (e.key === 'ArrowLeft') travelBy(step, 0);
        else if (e.key === 'ArrowRight') travelBy(-step, 0);
        else if (e.key === 'ArrowUp') travelBy(0, step);
        else if (e.key === 'ArrowDown') travelBy(0, -step);
        else if (e.key === 'Home') recenter();
        else handled = false;
        if (handled) { e.preventDefault(); render(); }
      }
      stage.addEventListener('keydown', onKey);
      elHome.addEventListener('click', recenter);

      // ---- resize + visibility --------------------------------------
      var ro = null, winResize = null;
      if (window.ResizeObserver) {
        ro = new window.ResizeObserver(function () { resize(); render(); });
        ro.observe(stage);
      } else {
        winResize = function () { resize(); render(); };
        window.addEventListener('resize', winResize); // removed in destroy()
      }

      // recolour on day/night inversion
      var offState = api.onStateChange ? api.onStateChange(function () { clearVarCache(); needsDraw = true; render(); }) : null;

      // No persistent rAF loop: the tiling is static and one render() is
      // always correct. loop.start() only spins briefly during a drag/keypress
      // (each tick draws once, then idles); onVisible pauses it offscreen.
      api.onVisible(stage, function () {
        visible = true; resize(); render();
      }, function () {
        visible = false; loop.stop();
      });

      // first paint (in case onVisible fires late)
      resize();
      render();

      return {
        destroy: function () {
          loop.stop();
          if (ro) ro.disconnect();
          if (winResize) window.removeEventListener('resize', winResize);
          if (typeof offState === 'function') offState();
          stage.removeEventListener('keydown', onKey);
          elHome.removeEventListener('click', recenter);
          if (!reduced) {
            stage.removeEventListener('pointerdown', onDown);
            stage.removeEventListener('pointermove', onMove);
            stage.removeEventListener('pointerup', onUp);
            stage.removeEventListener('pointercancel', onUp);
          }
          root.classList.remove('plate--circle-limit');
          root.innerHTML = '';
        }
      };
    }
  };
})();
